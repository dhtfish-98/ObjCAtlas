- (BOOL)atlas_shouldExpandType:(ObjCAtlasType *)atlas_type;
{
    ObjCAtlasStructureInfo *atlas_info;
    NSString *atlas_name = [atlas_type.atlas_typeName description];
    if ([@"?" isEqualToString:atlas_name]) {
        NSString *atlas_key = atlas_type.atlas_reallyBareTypeString;
        atlas_info = atlas__phase3_anonStructureInfo[atlas_key];
        if (atlas_info == nil) {
            // Look for an exception
            atlas_info = atlas__phase3_anonExceptions[atlas_type.atlas_typeString];
        }
    } else {
        atlas_info = atlas__phase3_namedStructureInfo[atlas_name];
        if (atlas_info == nil) {
            atlas_info = atlas__phase3_nameExceptions[atlas_type.atlas_typeString];
            if (atlas_info != nil) {
                //NSLog(@"[%@] %s, found phase3 name exception... %@", identifier, __cmd, [info shortDescription]);
                //return NO;
            }
        }
    }

    return [self atlas_shouldExpandStructureInfo:atlas_info];
}

