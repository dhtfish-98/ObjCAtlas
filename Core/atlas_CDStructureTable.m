- (void)atlas_appendNamedStructuresToString:(NSMutableString *)atlas_resultString
                            atlas_formatter:(ObjCAtlasTypeFormatter *)atlas_typeFormatter
                             atlas_markName:(NSString *)atlas_markName;
{
    BOOL atlas_hasAddedMark = NO;
    BOOL atlas_hasShownExceptions = NO;

    for (NSString *atlas_key in [[atlas__phase3_namedStructureInfo allKeys] sortedArrayUsingSelector:@selector(compare:)]) {
        ObjCAtlasStructureInfo *atlas_info = atlas__phase3_namedStructureInfo[atlas_key];
        BOOL atlas_shouldShow = ![self atlas_shouldExpandStructureInfo:atlas_info];
        if (atlas_shouldShow || atlas_debugNamedStructures) {
            if (atlas_hasAddedMark == NO) {
                [atlas_resultString appendFormat:@"#pragma mark %@\n\n", atlas_markName];
                atlas_hasAddedMark = YES;
            }

            ObjCAtlasType *atlas_type = atlas_info.type;
            if ([atlas_typeFormatter.atlas_typeController atlas_shouldShowName:[atlas_type.atlas_typeName description]]) {
                if (atlas_debugNamedStructures) {
                    [atlas_resultString appendFormat:@"// would normally show? %u\n", atlas_shouldShow];
                    [atlas_resultString appendFormat:@"// depth: %lu, ref count: %lu, used in method? %u\n", atlas_info.type.atlas_structureDepth, atlas_info.atlas_referenceCount, atlas_info.atlas_isUsedInMethod];
                }
                NSString *atlas_formattedString = [atlas_typeFormatter atlas_formatVariable:nil atlas_type:atlas_type];
                if (atlas_formattedString != nil) {
                    [atlas_resultString appendString:atlas_formattedString];
                    [atlas_resultString appendString:@";\n\n"];
                }
            }
        }
    }

    for (ObjCAtlasStructureInfo *atlas_info in [[atlas__phase3_nameExceptions allValues] sortedArrayUsingSelector:@selector(ascendingCompareByStructureDepth:)]) {
        BOOL atlas_shouldShow = ![self atlas_shouldExpandStructureInfo:atlas_info];
        if (atlas_shouldShow || atlas_debugNamedStructures) {
            if (atlas_hasAddedMark == NO) {
                [atlas_resultString appendFormat:@"#pragma mark %@\n\n", atlas_markName];
                atlas_hasAddedMark = YES;
            }

            if (atlas_hasShownExceptions == NO) {
                [atlas_resultString appendString:@"#if 0\n"];
                [atlas_resultString appendString:@"// Names with conflicting types:\n"];
                atlas_hasShownExceptions = YES;
            }

            ObjCAtlasType *atlas_type = atlas_info.type;
            if ([atlas_typeFormatter.atlas_typeController atlas_shouldShowName:[atlas_type.atlas_typeName description]]) {
                if (atlas_debugNamedStructures) {
                    [atlas_resultString appendFormat:@"// depth: %lu, ref count: %lu, used in method? %u\n", atlas_info.type.atlas_structureDepth, atlas_info.atlas_referenceCount, atlas_info.atlas_isUsedInMethod];
                    //[resultString appendFormat:@"// typedefName: %@\n", [info typedefName]];
                }
                NSString *atlas_formattedString = [atlas_typeFormatter atlas_formatVariable:nil atlas_type:atlas_type];
                if (atlas_formattedString != nil) {
                    [atlas_resultString appendFormat:@"typedef %@ %@;\n\n", atlas_formattedString, atlas_info.atlas_typedefName];
                }
            }
        }
    }
    if (atlas_hasShownExceptions)
        [atlas_resultString appendString:@"#endif\n\n"];

    if (atlas_debugNamedStructures) {
        [atlas_resultString appendString:@"\n// Name exceptions:\n"];
        for (ObjCAtlasStructureInfo *atlas_info in [[atlas__phase3_nameExceptions allValues] sortedArrayUsingSelector:@selector(ascendingCompareByStructureDepth:)])
            [atlas_resultString appendFormat:@"// %@\n", [atlas_info atlas_shortDescription]];
        [atlas_resultString appendString:@"\n"];
    }
}

- (void)atlas_appendTypedefsToString:(NSMutableString *)atlas_resultString
                     atlas_formatter:(ObjCAtlasTypeFormatter *)atlas_typeFormatter
                      atlas_markName:(NSString *)atlas_markName;
{
    BOOL atlas_hasAddedMark = NO;
    BOOL atlas_hasShownExceptions = NO;

    for (ObjCAtlasStructureInfo *atlas_info in [[atlas__phase3_anonStructureInfo allValues] sortedArrayUsingSelector:@selector(ascendingCompareByStructureDepth:)]) {
        BOOL atlas_shouldShow = ![self atlas_shouldExpandStructureInfo:atlas_info];
        if (atlas_shouldShow || atlas_debugAnonStructures) {
            if (atlas_hasAddedMark == NO) {
                [atlas_resultString appendFormat:@"#pragma mark %@\n\n", atlas_markName];
                atlas_hasAddedMark = YES;
            }

            if (atlas_debugAnonStructures) {
                [atlas_resultString appendFormat:@"// would normally show? %u\n", atlas_shouldShow];
                [atlas_resultString appendFormat:@"// %@\n", atlas_info.type.atlas_reallyBareTypeString];
                [atlas_resultString appendFormat:@"// depth: %lu, ref: %lu, used in method? %u\n", atlas_info.type.atlas_structureDepth, atlas_info.atlas_referenceCount, atlas_info.atlas_isUsedInMethod];
            }

            NSString *atlas_formattedString = [atlas_typeFormatter atlas_formatVariable:nil atlas_type:atlas_info.type];
            if (atlas_formattedString != nil) {
                [atlas_resultString appendFormat:@"typedef %@ %@;\n\n", atlas_formattedString, atlas_info.atlas_typedefName];
            }
        }
    }

    // TODO: (2009-08-25) Need same ref count rules for anon exceptions.
    for (ObjCAtlasStructureInfo *atlas_info in [[atlas__phase3_anonExceptions allValues] sortedArrayUsingSelector:@selector(ascendingCompareByStructureDepth:)]) {
        BOOL atlas_shouldShow = ![self atlas_shouldExpandStructureInfo:atlas_info];
        if (atlas_shouldShow || atlas_debugAnonStructures) {
            if (atlas_hasAddedMark == NO) {
                [atlas_resultString appendFormat:@"#pragma mark %@\n\n", atlas_markName];
                atlas_hasAddedMark = YES;
            }

            if (atlas_hasShownExceptions == NO) {
                [atlas_resultString appendString:@"// Ambiguous groups\n"];
                atlas_hasShownExceptions = YES;
            }

            if (atlas_debugAnonStructures) {
                [atlas_resultString appendFormat:@"// %@\n", atlas_info.type.atlas_reallyBareTypeString];
                [atlas_resultString appendFormat:@"// depth: %lu, ref: %lu, used in method? %u\n", atlas_info.type.atlas_structureDepth, atlas_info.atlas_referenceCount, atlas_info.atlas_isUsedInMethod];
            }

            NSString *atlas_formattedString = [atlas_typeFormatter atlas_formatVariable:nil atlas_type:atlas_info.type];
            if (atlas_formattedString != nil) {
                //[resultString appendFormat:@"%@;\n\n", formattedString];
                [atlas_resultString appendFormat:@"typedef %@ %@;\n\n", atlas_formattedString, atlas_info.atlas_typedefName];
            }
        }
    }

    for (NSString *atlas_key in [[atlas__phase3_namedStructureInfo allKeys] sortedArrayUsingSelector:@selector(compare:)]) {
        ObjCAtlasStructureInfo *atlas_info = atlas__phase3_namedStructureInfo[atlas_key];
        BOOL atlas_shouldShow = atlas_info.type.atlas_isTemplateType && atlas_info.atlas_isUsedInMethod;
        if (atlas_shouldShow || atlas_debugAnonStructures) {
            if (atlas_hasAddedMark == NO) {
                [atlas_resultString appendFormat:@"#pragma mark %@\n\n", atlas_markName];
                atlas_hasAddedMark = YES;
            }

            if (atlas_hasShownExceptions == NO) {
                [atlas_resultString appendString:@"// Template types\n"];
                atlas_hasShownExceptions = YES;
            }

            if (atlas_debugAnonStructures) {
                [atlas_resultString appendFormat:@"// %@\n", atlas_info.type.atlas_reallyBareTypeString];
                [atlas_resultString appendFormat:@"// depth: %lu, ref: %lu, used in method? %u\n", atlas_info.type.atlas_structureDepth, atlas_info.atlas_referenceCount, atlas_info.atlas_isUsedInMethod];
            }

            NSString *atlas_formattedString = [atlas_typeFormatter atlas_formatVariable:nil atlas_type:atlas_info.type];
            if (atlas_formattedString != nil) {
                //[resultString appendFormat:@"%@;\n\n", formattedString];
                [atlas_resultString appendFormat:@"typedef %@ %@;\n\n", atlas_formattedString, atlas_info.atlas_typedefName];
            }
        }
    }
}

- (BOOL)atlas_shouldExpandStructureInfo:(ObjCAtlasStructureInfo *)atlas_info;
{
    return (atlas_info == nil)
        || (atlas_info.atlas_isUsedInMethod == NO
            && (atlas_info.type.atlas_isTemplateType == NO || atlas_info.atlas_isUsedInMethod == NO)
            && atlas_info.atlas_referenceCount < 2
            && (([atlas_info.name hasPrefix:@"_"] && [atlas_info.name atlas_hasUnderscoreCapitalPrefix] == NO) // TODO: Don't need the first hasPrefix check now.
                || [@"?" isEqualToString:atlas_info.name]));
}

